export function cartTotalCents(cart: Record<string, number>) {
  return products.reduce((total, product) => total + product.priceCents * Math.max(0, cart[product.name] ?? 0), 0);
}

export function formatPrice(cents: number, ro = false) {
  return new Intl.NumberFormat(ro ? "ro-RO" : "en-IE", { style: "currency", currency: "EUR" }).format(cents / 100);
}
