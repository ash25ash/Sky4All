class LangSwitcher extends StatelessWidget {
  final I18nService i18n;
  const LangSwitcher({super.key, required this.i18n});

  @override
  Widget build(BuildContext context) {
    return Container(
      decoration: BoxDecoration(
        color: Sky4AllPalette.card,
        borderRadius: BorderRadius.circular(999),
        border: Border.all(color: Sky4AllPalette.border),
      ),
      clipBehavior: Clip.antiAlias,
      child: Row(
        mainAxisSize: MainAxisSize.min,
        children: ['en', 'ro'].map((code) {
          final active = i18n.lang == code;
          return InkWell(
            onTap: () => i18n.setLang(code),
            child: Container(
              padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 4),
              color: active ? Sky4AllPalette.primary : Colors.transparent,
              child: Text(
                code.toUpperCase(),
                style: TextStyle(
                  fontSize: 12,
                  fontWeight: FontWeight.w700,
                  color: active
                      ? Sky4AllPalette.primaryForeground
                      : Sky4AllPalette.mutedForeground,
                ),
              ),
            ),
          );
        }).toList(),
      ),
    );
  }
}
